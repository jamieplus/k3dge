_REQUIRED_KEYS = (
    "grammar", "package", "lang_func", "lang_name", "suffixes", "wrapper", "wrapper_kw",
    "fn", "container", "body", "member", "type",
    "lexical_nodes", "lexical_markers", "lexical",
)


class ExtractorConfigError(ValueError):
    """Misconfigured `.agent/extractors.toml` — loud, never silent."""


def _toml_loads(text: str) -> dict:
    try:
        import tomllib
    except ModuleNotFoundError:
        try:
            import tomli as tomllib  # type: ignore[no-redef]
        except ImportError:
            tomllib = None  # type: ignore[assignment]
    if tomllib is None:
        raise ExtractorConfigError("tomllib/tomli unavailable; cannot read .agent/extractors.toml")
    try:
        data = tomllib.loads(text)
    except Exception as exc:
        raise ExtractorConfigError(f"TOML parse failed in .agent/extractors.toml: {exc}") from exc
    if not isinstance(data, dict):
        raise ExtractorConfigError(".agent/extractors.toml must be a table")
    return data


def _check_row(name: str, row: Any) -> Dict[str, Any]:
    if not isinstance(row, dict):
        raise ExtractorConfigError(f"[languages.{name}] must be a table")
    missing = [k for k in _REQUIRED_KEYS if k not in row]
    if missing:
        raise ExtractorConfigError(f"[languages.{name}] missing keys: {', '.join(missing)}")
    extra = [k for k in row if k not in _REQUIRED_KEYS]
    if extra:
        raise ExtractorConfigError(f"[languages.{name}] unknown keys: {', '.join(extra)} (typo?)")
    for k in ("grammar", "package", "lang_func", "lang_name"):
        if not isinstance(row[k], str) or not row[k].strip():
            raise ExtractorConfigError(f"[languages.{name}] '{k}' must be a non-empty string")
    if not isinstance(row["wrapper_kw"], str):
        raise ExtractorConfigError(f"[languages.{name}] 'wrapper_kw' must be a string")
    for k in ("suffixes", "wrapper", "fn", "container", "body", "member", "type",
              "lexical_nodes", "lexical_markers"):
        v = row[k]
        if not isinstance(v, list) or not all(isinstance(x, str) for x in v):
            raise ExtractorConfigError(f"[languages.{name}] '{k}' must be a list of strings")
    if not row["suffixes"] or not all(s.startswith(".") for s in row["suffixes"]):
        raise ExtractorConfigError(f"[languages.{name}] 'suffixes' must be non-empty and dot-prefixed")
    if not isinstance(row["lexical"], bool):
        raise ExtractorConfigError(f"[languages.{name}] 'lexical' must be a boolean")
    return dict(row)


def resolve_languages(workspace: Path) -> Dict[str, Dict[str, Any]]:
    """Merge builtin table with `.agent/extractors.toml`.

    - No toml file -> `enable` defaults to `["typescript"]` (preserve legacy behavior).
    - `enable` names resolve against builtins; unknown name without a custom row -> error.
    - `[languages.<name>]` replaces the builtin row wholesale (no per-field merge).
    - Custom rows are enabled by presence.
    Returns ordered {name: row} (enable order first, then customs).
    """
    enable: List[str] = ["typescript"]
    customs: Dict[str, Any] = {}
    cfg_path = workspace / CONFIG_REL
    if cfg_path.is_file():
        data = _toml_loads(cfg_path.read_text(encoding="utf-8"))
        raw_enable = data.get("enable", ["typescript"])
        if not isinstance(raw_enable, list) or not all(isinstance(x, str) for x in raw_enable):
            raise ExtractorConfigError("'enable' must be a list of strings")
        enable = list(raw_enable)
        raw_langs = data.get("languages", {})
        if not isinstance(raw_langs, dict):
            raise ExtractorConfigError("'languages' must be a table")
        customs = raw_langs
    resolved: Dict[str, Dict[str, Any]] = {}
    for name in enable:
        if name in customs:
            resolved[name] = _check_row(name, customs[name])
        elif name in DEFAULT_LANGS:
            resolved[name] = dict(DEFAULT_LANGS[name])
        else:
            known = sorted(set(DEFAULT_LANGS) | set(customs))
            raise ExtractorConfigError(
                f"unknown language '{name}' in 'enable' (available: {', '.join(known)}); "
                f"define it under [languages.{name}]"
            )
    for name, row in customs.items():
        if name not in resolved:
            resolved[name] = _check_row(name, row)
    return resolved


def _tup(items: List[str]) -> str:
    return "(" + ", ".join(f'"{x}"' for x in items) + ("," if len(items) == 1 else "") + ")"


def render_plugin(name: str, row: Dict[str, Any]) -> str:
    """Render a self-contained plugin module. Deterministic: same row -> same bytes."""
    slug = "".join(c if (c.isalnum() or c == "_") else "_" for c in name).strip("_") or "lang"
    cls = "".join(p[:1].upper() + p[1:] for p in slug.split("_") if p) + "Extractor"
    lines: List[str] = [
        MARKER + " — do not edit.",
        f"# Source: .agent/extractors.toml + builtin table (`src/k3dge/engine/extractor_gen.py`).",
        "# To customize: copy this file to a new name, remove this header",
        "# (markerless files are never pruned or overwritten), and edit freely.",
        f'"""{{}} interface extractor plugin (generated).'.format(name),
        "",
        "Requires the grammar package (see pip hint from `k3dge extractor sync`).",
        "Without it, matching files are silently skipped by the gate: `extract()`",
        "raises `ImportError`, which `engine/contract.py` treats as a skip signal",
        "(never fatal) — see `extract_python_interface` caller's `except ImportError`.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from pathlib import Path",
        "from typing import List, Optional",
        "",
        "from k3dge.engine.contract import ContractExtractor, register_extractor",
        "",
        '_IGNORED_DIRS = {".git", ".mypy_cache", ".next", ".pytest_cache", ".venv", '
        '"__pycache__", "build", "coverage", "dist", "node_modules", "out", "vendor", "venv"}',
        '_GENERATED_MARKERS = (".generated.", ".min.")',
        '_GENERATED_SUFFIXES = (".d.ts",)',
        "_PARSER = None",
        "",
        "",
        "def _is_generated(path: Path) -> bool:",
        "    name = path.name",
        "    return any(m in name for m in _GENERATED_MARKERS) or name.endswith(_GENERATED_SUFFIXES)",
        "",
        "",
        "def _slice(source: bytes, node) -> str:",
        '    text = source[node.start_byte : node.end_byte].decode("utf-8", "replace")',
        '    return "".join(ch for ch in text if ch in "\\n\\t" or ch.isprintable()).strip()',
        "",
        "",
        "def _strip_impl_body(text: str) -> str:",
        '    """Drop the first `{ ... }` implementation body; keep signature / type members."""',
        '    brace = text.find("{")',
        "    if brace == -1:",
        "        return text.rstrip()",
        "    return text[:brace].rstrip()",
        "",
        "",
    ]
    if row["container"]:
        lines += [
            "def _container_signature(source: bytes, node) -> str:",
            "    header = _strip_impl_body(_slice(source, node))",
            "    methods: List[str] = []",
            "    for child in node.children:",
            f"        if child.type not in {_tup(row['body'])}:",
            "            continue",
            "        for member in child.children:",
            f"            if member.type in {_tup(row['member'])}:",
            "                sig = _strip_impl_body(_slice(source, member))",
            "                if sig:",
            '                    methods.append("  " + sig)',
            "    if not methods:",
            "        return header",
            '    return header + "\\n" + "\\n".join(methods)',
            "",
            "",
        ]
    # _decl_signature branches, assembled in fixed order (matches legacy _ts.py
    # branch order for the typescript row, so generated output is identical).
    search_sets = [f"{_tup(row['fn'])}", f"{_tup(row['container'])}", f"{_tup(row['type'])}"]
    if row["lexical_nodes"]:
        search_sets.append(_tup(row["lexical_nodes"]))
    branches: List[str] = []
    if row["wrapper"]:
        branches.append(
            f"    if node.type in {_tup(row['wrapper'])}:\n"
            "        inner = None\n"
            "        for child in node.children:\n"
            f"            if child.type in {' + '.join(search_sets)}:\n"
            "                inner = child\n"
            "                break\n"
            "        if inner is None:\n"
            "            return _slice(source, node)\n"
            "        return _decl_signature(source, inner, exported=True)"
        )
    if row["container"]:
        branches.append(
            f"    {'el' if branches else ''}if node.type in {_tup(row['container'])}:\n"
            "        text = _container_signature(source, node)"
        )
    branches.append(
        f"    {'el' if branches else ''}if node.type in {_tup(row['fn'])}:\n"
        "        text = _strip_impl_body(_slice(source, node))"
    )
    branches.append(
        f"    elif node.type in {_tup(row['type'])}:\n"
        "        text = _slice(source, node)"
    )
    if row["lexical"]:
        markers = " or ".join(f'"{m}" in text' for m in row["lexical_markers"])
        branches.append(
            f"    elif node.type in {_tup(row['lexical_nodes'])}:\n"
            "        if not exported:\n"
            "            return None\n"
            "        text = _slice(source, node)\n"
            f"        if {markers}:\n"
            "            text = _strip_impl_body(text)"
        )
    branches.append("    else:\n        return None")
    decl = ["def _decl_signature(source: bytes, node, exported: bool = False) -> Optional[str]:"] + branches
    if row["wrapper_kw"]:
        kw = row["wrapper_kw"]
        decl += [
            f'    if exported and not text.startswith("{kw}"):',
            f'        text = "{kw} " + text',
        ]
    decl += ["    return text", "", ""]
    lines += decl
    lines += [
        f"def extract_{slug}_interface(path: Path) -> str:",
        "    global _PARSER",
        "    try:",
        "        from tree_sitter import Language, Parser",
        "        import importlib",
        f"        _grammar = importlib.import_module(\"{row['grammar']}\")",
        "    except ImportError as exc:",
        f"        raise ImportError(\"{row['package']} not installed; pip install {row['package']}\") from exc",
        "    if _PARSER is None:",
        "        try:",
        f"            language = Language(_grammar.{row['lang_func']}())",
        "        except TypeError:",
        f"            language = Language(_grammar.{row['lang_func']}(), \"{row['lang_name']}\")  # type: ignore[call-arg]",
        "        try:",
        "            parser = Parser(language)  # 0.21+",
        "        except TypeError:",
        "            parser = Parser()",
        "            parser.language = language  # type: ignore[attr-defined]",
        "        _PARSER = parser",
        "    parser = _PARSER",
        "    source = path.read_bytes()",
        "    tree = parser.parse(source)",
        "    lines = []",
        "    for node in tree.root_node.children:",
        "        text = _decl_signature(source, node)",
        "        if text:",
        "            lines.append(text)",
        '    return "\\n".join(lines)',
        "",
        "",
        f"class {cls}(ContractExtractor):",
        "    def can_handle(self, path: Path) -> bool:",
        f"        return (path.suffix in {_tup(row['suffixes'])} and not _IGNORED_DIRS.intersection(path.parts)"
        " and not _is_generated(path))",
        "",
        "    def extract(self, path: Path, include_doc: bool = False) -> str:",
        f"        return extract_{slug}_interface(path)",
        "",
        "",
        f"register_extractor({cls}())",
        "",
    ]
    return "\n".join(lines)


def sync_extractors(workspace: Path) -> Dict[str, Any]:
    """Render all resolved languages into `.agent/extractors/`. Idempotent.

    Writes only changed files; prunes stale GENERATED files (marker-headed `.py`
    whose stem is no longer enabled; markerless files, README and `_*.py` are
    never touched). Missing grammar packages are reported, not fatal.
    Returns {"written": [...], "pruned": [...], "missing": [(name, pip_cmd)]}.
    """
    import importlib.util

    resolved = resolve_languages(workspace)
    plugdir = workspace / PLUGDIR_REL
    plugdir.mkdir(parents=True, exist_ok=True)
    written: List[str] = []
    for name, row in resolved.items():
        text = render_plugin(name, row)
        dest = plugdir / f"{name}.py"
        try:
            existing = dest.read_text(encoding="utf-8")
        except OSError:
            existing = None
        if existing != text:
            dest.write_text(text, encoding="utf-8")
            written.append(name)
    pruned: List[str] = []
    for p in sorted(plugdir.glob("*.py")):
        if p.name.startswith("_") or p.stem in resolved:
            continue
        try:
            head = p.read_text(encoding="utf-8")[:200]
        except OSError:
            continue
        if MARKER in head:
            p.unlink()
            pruned.append(p.name)
    missing: List[Tuple[str, str]] = []
    for name, row in resolved.items():
        if importlib.util.find_spec(row["grammar"]) is None:
            missing.append((name, f"pip install {row['package']}"))
    return {"written": written, "pruned": pruned, "missing": missing}


def describe_extractors(workspace: Path) -> List[str]:
    """Human-readable lines for `k3dge extractor list`."""
    import importlib.util

    resolved = resolve_languages(workspace)
    plugdir = workspace / PLUGDIR_REL
    out: List[str] = []
    for name, row in sorted(resolved.items()):
        installed = importlib.util.find_spec(row["grammar"]) is not None
        present = (plugdir / f"{name}.py").is_file()
        out.append(
            f"- {name}: suffixes={','.join(row['suffixes'])} package={row['package']}"
            f"({'installed' if installed else 'NOT INSTALLED'})"
            f" plugin={'present' if present else 'missing — run `k3dge extractor sync`'}"
        )
    return out
